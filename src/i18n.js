export function translate(locale, key, values = {}) {
  const lookup = language => key.split('.').reduce((object, part) => object?.[part], messages[language])
  const text = lookup(locale) ?? lookup('en') ?? key
  return String(text).replace(/\{(\w+)\}/g, (_, name) => values[name] ?? '{' + name + '}')
}
